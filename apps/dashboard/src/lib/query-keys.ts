/** Query keys in one place so invalidation stays consistent. */
export const qk = {
  me: ['me'] as const,
  system: ['system'] as const,
  bootstrap: ['bootstrap-status'] as const,
  organizations: ['organizations'] as const,
  organization: (orgId: string) => ['organization', orgId] as const,
  members: (orgId: string) => ['members', orgId] as const,
  projects: (orgId: string) => ['projects', orgId] as const,
  project: (projectId: string) => ['project', projectId] as const,
  credentials: (projectId: string, includeRevoked: boolean) => ['credentials', projectId, includeRevoked] as const,
  jobs: (projectId: string, filters?: object) => ['jobs', projectId, filters ?? {}] as const,
  job: (projectId: string, jobId: string) => ['job', projectId, jobId] as const,
  queues: (projectId: string) => ['queues', projectId] as const,
  queue: (projectId: string, name: string) => ['queue', projectId, name] as const,
  executions: (projectId: string, filters?: object) => ['executions', projectId, filters ?? {}] as const,
  execution: (projectId: string, executionId: string) => ['execution', projectId, executionId] as const,
  executionLogs: (projectId: string, executionId: string) => ['execution-logs', projectId, executionId] as const,
  stats: (projectId: string, params?: object) => ['stats', projectId, params ?? {}] as const,
  timeseries: (projectId: string, params?: object) => ['timeseries', projectId, params ?? {}] as const,
  upcoming: (projectId: string, params?: object) => ['upcoming', projectId, params ?? {}] as const,
  agents: (projectId: string) => ['agents', projectId] as const,
  agent: (projectId: string, agentId: string) => ['agent', projectId, agentId] as const,
  workers: ['workers'] as const,
  worker: (workerId: string) => ['worker', workerId] as const,
  activity: (orgId: string, filters?: object) => ['activity', orgId, filters ?? {}] as const,
};
